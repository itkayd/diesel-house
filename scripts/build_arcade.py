"""Build the Night Raid arcade atlas (src/games/nightRaid.ts) from Ninja Adventure (CC0).

    python scripts/build_arcade.py

Writes public/assets/arcade/nightraid.png and src/games/nightraid.json ({frames: {name: [x, y, w, h]}}).
Enemies use their front-facing walk frames; the boss is the Giant Spirit; plus shurikens, fireballs
(turned to fall downwards), the explosion, food to catch, a heart and a shield.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NA = os.path.join(ROOT, 'assets', 'raw', 'redesign-packs', 'Ninja Adventure - Asset Pack', 'Ninja Adventure - Asset Pack')
OUT_PNG = os.path.join(ROOT, 'public', 'assets', 'arcade', 'nightraid.png')
OUT_JSON = os.path.join(ROOT, 'src', 'games', 'nightraid.json')

ENEMIES = {
    'bat': 'Actor/Monster/BlueBat/SpriteSheet.png',
    'bat2': 'Actor/Monster/YellowsBat/SpriteSheet.png',
    'skull': 'Actor/Monster/Skull/SpriteSheet.png',
    'skull2': 'Actor/Monster/SkullBlue/SpriteSheet.png',
    'spirit': 'Actor/Monster/Spirit/SpriteSheet.png',
    'lantern': 'Actor/Monster/LanternRed/SpriteSheet.png',
    'eye': 'Actor/Monster/Eye/Eye.png',
    'flam': 'Actor/Monster/Flam/SpriteSheet.png',
    'octopus': 'Actor/Monster/Octopus/SpriteSheet.png',
    'dragon': 'Actor/Monster/Dragon/SpriteSheet.png',
}


def strip(path, n, w=None, h=None, rotate=0):
    im = Image.open(os.path.join(NA, path)).convert('RGBA')
    w = w or im.width // n
    h = h or im.height
    out = []
    for i in range(n):
        f = im.crop((i * w, 0, i * w + w, h))
        if rotate:
            f = f.rotate(rotate, expand=True)
        out.append(f)
    return out


def main():
    if not os.path.isdir(NA):
        sys.exit(f'Ninja Adventure not found at {NA}')
    pieces = []  # (name, image)
    for key, path in ENEMIES.items():
        sheet = Image.open(os.path.join(NA, path)).convert('RGBA')
        for r in range(4):  # column 0 = facing down, rows = walk steps
            pieces.append((f'{key}_{r}', sheet.crop((0, r * 16, 16, r * 16 + 16))))
    for i, f in enumerate(strip('Actor/Boss/GiantSpirit/Idle.png', 5)):
        pieces.append((f'boss_{i}', f))
    for i, f in enumerate(strip('Actor/Boss/GiantSpirit/Hit.png', 3)):
        pieces.append((f'bosshit_{i}', f))
    for i, f in enumerate(strip('FX/Elemental/Explosion/SpriteSheet.png', 9)):
        pieces.append((f'boom_{i}', f))
    for i, f in enumerate(strip('FX/Projectile/Shuriken.png', 2)):
        pieces.append((f'shuriken_{i}', f))
    for i, f in enumerate(strip('FX/Projectile/ShurikenMagic.png', 2)):
        pieces.append((f'magic_{i}', f))
    for i, f in enumerate(strip('FX/Projectile/Fireball.png', 4, rotate=-90)):
        pieces.append((f'fire_{i}', f))
    for i, f in enumerate(strip('FX/Magic/Shield/SpriteSheetBlue.png', 6)):
        pieces.append((f'shield_{i}', f))
    for name, path in [('onigiri', 'Items/Food/Onigiri.png'), ('cookie', 'Items/Food/FortuneCookie.png'), ('noodle', 'Items/Food/Noodle.png'),
                       ('meat', 'Items/Food/Meat.png'), ('heart', 'Ui/Receptacle/IconHeart.png'), ('potion', 'Items/Potion/Heart.png')]:
        pieces.append((name, Image.open(os.path.join(NA, path)).convert('RGBA')))

    # Shelf packing, 256 px wide.
    W = 256
    x = y = row_h = 0
    frames = {}
    for name, im in pieces:
        if x + im.width > W:
            x, y, row_h = 0, y + row_h + 1, 0
        frames[name] = [x, y, im.width, im.height]
        x += im.width + 1
        row_h = max(row_h, im.height)
    atlas = Image.new('RGBA', (W, y + row_h), (0, 0, 0, 0))
    for name, im in pieces:
        fx, fy, _, _ = frames[name]
        atlas.paste(im, (fx, fy))
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    atlas.save(OUT_PNG, optimize=True)
    with open(OUT_JSON, 'w') as f:
        json.dump({'note': 'Generated by scripts/build_arcade.py from Ninja Adventure (CC0, pixel-boy). Do not edit by hand.', 'frames': frames}, f)
        f.write('\n')
    print(f'{len(frames)} frames -> {OUT_PNG} ({atlas.width}x{atlas.height}), {OUT_JSON}')


if __name__ == '__main__':
    main()
