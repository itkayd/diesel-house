"""Build the animals atlas (REDESIGN.md R4: animals around the house, and pets) from Ninja Adventure (CC0).

    python scripts/build_animals.py

Each Ninja animal sheet is 2 side-view frames (sitting, then moving), facing right. They're cut and
centred, feet on the bottom row, into 24 x 24 cells: animal i uses frames 2i (still) and 2i + 1 (moving).
Writes public/assets/animals/animals.png and src/house/animals.json.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'raw', 'redesign-packs', 'Ninja Adventure - Asset Pack', 'Ninja Adventure - Asset Pack', 'Actor', 'Animal')
OUT_PNG = os.path.join(ROOT, 'public', 'assets', 'animals', 'animals.png')
OUT_JSON = os.path.join(ROOT, 'src', 'house', 'animals.json')
CELL = 24

# key, name, file (side-view, 2 frames)
ANIMALS = [
    ('cat', 'Ginger cat', 'Cat/SpriteSheet.png'),
    ('cat_black', 'Black cat', 'CatBlack/SpriteSheet.png'),
    ('cat_orange', 'Tabby cat', 'CatOrange/SpriteSheet.png'),
    ('cat_white', 'White cat', 'CatWhite/SpriteSheet.png'),
    ('dog', 'Pup', 'Dog/SpriteSheet.png'),
    ('dog2', 'Terrier', 'Dog2/SpriteSheet.png'),
    ('dog_black', 'Black dog', 'DogBlack/SpriteSheet.png'),
    ('dog_yellow', 'Golden dog', 'DogYellow/SpriteSheet.png'),
    ('chicken', 'Chicken', 'Chicken/SpriteSheetWhite.png'),
    ('chick_brown', 'Brown hen', 'Chicken/SpriteSheetBrown.png'),
    ('frog', 'Frog', 'Frog/SpriteSheet.png'),
    ('parrot', 'Parrot', 'Parrot/SpriteSheetBlue.png'),
    ('parrot_red', 'Red parrot', 'Parrot/SpriteSheetRed.png'),
    ('pig', 'Pig', 'Pig/SpriteSheetPink.png'),
    ('racoon', 'Racoon', 'Racoon/SpriteSheet.png'),
    ('hamster', 'Hamster', 'Hamster/SpriteSheet.png'),
    ('monkey', 'Monkey', 'Monkey/SpriteSheetBrown.png'),
    ('lion_cub', 'Lion cub', 'LionCub/SpriteSheet.png'),
    ('cow', 'Cow', 'Cow/SpriteSheetWhiteSide.png'),
    ('horse', 'Horse', 'Horse/SpriteSheetBrownSide.png'),
    ('boar', 'Wild boar', 'WildBoar/SpriteSheet.png'),
]


def main():
    if not os.path.isdir(SRC):
        sys.exit(f'Ninja Adventure animals not found at {SRC}')
    atlas = Image.new('RGBA', (CELL * 2, CELL * len(ANIMALS)), (0, 0, 0, 0))
    out = []
    for i, (key, name, path) in enumerate(ANIMALS):
        sheet = Image.open(os.path.join(SRC, path)).convert('RGBA')
        fw = sheet.width // 2
        for f in range(2):
            frame = sheet.crop((f * fw, 0, f * fw + fw, sheet.height))
            box = frame.getbbox() or (0, 0, fw, sheet.height)
            frame = frame.crop(box)
            if frame.width > CELL or frame.height > CELL:
                sys.exit(f'{key} frame {f} is {frame.size}, bigger than {CELL} px')
            atlas.paste(frame, (f * CELL + (CELL - frame.width) // 2, i * CELL + CELL - frame.height))
        out.append({'key': key, 'name': name})
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    atlas.save(OUT_PNG, optimize=True)
    with open(OUT_JSON, 'w') as f:
        json.dump({'note': 'Generated by scripts/build_animals.py from Ninja Adventure (CC0, pixel-boy). Do not edit by hand.',
                   'cell': CELL, 'animals': out}, f, indent=1)
        f.write('\n')
    print(f'{len(out)} animals -> {OUT_PNG} ({atlas.width}x{atlas.height}), {OUT_JSON}')


if __name__ == '__main__':
    main()
